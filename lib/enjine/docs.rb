# frozen_string_literal: true

require "json"
require "fileutils"

module Enjine
  # Generates the reference docs and support matrix from Enjine.registry, so the
  # documentation always matches the code. `rake docs` writes them; a spec fails
  # when the committed files drift.
  module Docs
    CATEGORY_TITLES = {
      type: "Card types", supertype: "Supertypes", subtype: "Subtypes with rules",
      ability: "Abilities", cost: "Costs", effect: "Effects"
    }.freeze
    ROOT = File.expand_path("../..", __dir__)

    module_function

    # {relative path => content}
    def generate
      files = { "SUPPORTED.md" => supported }
      Primitive::CATEGORIES.each { |c| files["docs/reference/#{file_for(c)}.md"] = reference(c) }
      files["docs/reference/decisions.md"] = decisions
      files
    end

    def write(root = ROOT)
      generate.each do |path, content|
        full = File.join(root, path)
        FileUtils.mkdir_p(File.dirname(full))
        File.write(full, content)
      end
    end

    def supported
      lines = ["# Supported mechanics", "", generated_note, "",
               "Rules version: Comprehensive Rules effective #{RULES_VERSION}.", ""]
      Primitive::CATEGORIES.each do |category|
        lines << "## #{CATEGORY_TITLES.fetch(category)}" << ""
        entries = Enjine.registry.each(category).to_a
        if entries.empty?
          lines << "_None yet._" << ""
          next
        end
        lines << "| Name | Rules | Description |" << "| --- | --- | --- |"
        entries.each do |klass|
          lines << "| [`#{klass.primitive_name}`](docs/reference/#{file_for(category)}.md##{klass.primitive_name}) | " \
                   "#{klass.rules.join(", ")} | #{klass.description} |"
        end
        lines << ""
      end
      lines << "## Decisions" << "" << "See [docs/reference/decisions.md](docs/reference/decisions.md)." << ""
      lines.join("\n")
    end

    def reference(category)
      lines = ["# #{CATEGORY_TITLES.fetch(category)}", "", generated_note, ""]
      entries = Enjine.registry.each(category).to_a
      lines << "_None yet._" << "" if entries.empty?
      entries.each do |klass|
        lines << "## #{klass.primitive_name}" << "" << klass.description << ""
        lines << "Rules: #{klass.rules.map { "CR #{it}" }.join(", ")}" << "" unless klass.rules.empty?
        unless klass.params.empty?
          lines << "| Parameter | Description |" << "| --- | --- |"
          klass.params.each { |k, v| lines << "| `#{k}` | #{v} |" }
          lines << ""
        end
        lines << "```json" << JSON.pretty_generate(klass.example) << "```" << "" if klass.example
      end
      lines.join("\n")
    end

    def decisions
      lines = ["# Decisions", "", generated_note, "",
               "`game.pending_decision` returns the decision below; submit one of its `options`.", ""]
      Decisions::KINDS.sort.each do |kind, klass|
        lines << "## #{kind}" << "" << (klass.respond_to?(:doc) ? klass.doc : "") << ""
      end
      lines << "## Priority actions" << ""
      Actions::BY_TYPE.sort.each { |type, klass| lines << "- `#{type}` — #{klass.doc}" }
      lines << ""
      lines.join("\n")
    end

    def file_for(category) = category == :ability ? "abilities" : "#{category}s"

    def generated_note = "<!-- Generated by `rake docs` from the primitive registry. Do not edit. -->"
  end
end
